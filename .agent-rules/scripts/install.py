#!/usr/bin/env python3
"""Create and verify this host's agent-config symlink farm.

Every agent insists on finding rules, skills and subagents at its own path,
under its own filename. The content is authored once in `~/.agent-rules/` and
each agent's directory gets a symlink into it, so there are no copies to drift
apart.

    python3 install.py            # create anything missing
    python3 install.py --check    # report only, exit 1 if anything is missing

Deliberately conservative about which agents it touches:

  * A link is only created if its *parent agent directory already exists*
    (except `~/.gemini/config/`, which this script may create because
    Antigravity is installed and that is where it looks for global skills).
  * Codex links use `$CODEX_HOME` when set. The user skills path remains
    `~/.agents/skills`, which the installer creates once Codex exists.
  * A real file (not a symlink) sitting where a link belongs is reported as a
    conflict and left alone.

Codex's `$CODEX_HOME/AGENTS.md` is written at install time: `AGENTS.md`,
`host.md` and `harness/codex/codex.md` concatenated in that order, with in-tree
`` `../ `` pointers made absolute. A user-owned file at that path is left
alone.

Shared subagents reach Codex as generated `$CODEX_HOME/agents/<n>.toml`
files, Cursor as generated `~/.cursor/agents/<n>.md` files, and Antigravity as
generated `~/.gemini/config/agents/<n>.md` files (written, not linked: each
wants model inline, and Antigravity requires `subagent: true`), with the rungs
read from `effort-models.json`.

Cursor's `~/.cursor/hooks.json` is generated from the same lifecycle job
list as Codex (Codex event names mapped onto Cursor event names), plus
Cursor-only family-gate and subagentStop jobs. Unknown user hooks are
preserved. The tracked `.cursor/hooks.json` in this repo is checked
against that renderer.
"""

