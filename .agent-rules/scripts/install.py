def relative_target(link: Path, target: Path) -> str:
    try:
        return os.path.relpath(target, link.parent)
    except ValueError:
        return str(target)


def apply(item: Link) -> bool:
    """Create a missing link, or retarget a HOST-owned link after a layout move.

    A real file, or a symlink pointing outside HOST, is left alone.
    """
    if item.link.is_symlink():
        try:
            current = item.link.resolve()
            desired = item.target.resolve()
        except OSError:
            return False
        if current == desired:
            return True
        try:
            current.relative_to(HOST)
            desired.relative_to(HOST)
        except ValueError:
            return False
        item.link.unlink()
        item.link.symlink_to(relative_target(item.link, item.target))
        return True
    if item.link.exists():
        return False
    if item.create_parents:
        item.link.parent.mkdir(parents=True, exist_ok=True)
    item.link.symlink_to(relative_target(item.link, item.target))
    return True


