def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repo", type=Path, help="project root")
    parser.add_argument(
        "--preset",
        choices=sorted(PRESETS),
        help="named project preset (display, framing, guards, critical)",
    )
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    repo = args.repo.resolve()
    name = args.preset or repo.name
    if name not in PRESETS:
        print(f"error: no preset for {name}; pass --preset", file=sys.stderr)
        return 1
    cfg = PRESETS[name]
    return migrate(
        repo,
        display=cfg["display"],
        framing=cfg["framing"],
        critical=cfg["critical"],
        guards=cfg["guards"],
        hooks_note=cfg["hooks_note"],
        force=args.force,
    )


if __name__ == "__main__":
    raise SystemExit(main())
