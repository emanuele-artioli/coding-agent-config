def ensure_symlink(link: Path, target: str) -> None:
    if link.is_symlink() or link.exists():
        if link.is_symlink() and str(link.readlink()) == target:
            return
        if link.is_dir() and not link.is_symlink():
            shutil.rmtree(link)
        else:
            link.unlink()
    link.symlink_to(target)


def flip_skills_to_claude(repo: Path) -> None:
    """Prefer real skills under .claude/; .agents/skills -> symlink."""
    agents_skills = repo / ".agents" / "skills"
    claude_skills = repo / ".claude" / "skills"
    if claude_skills.is_symlink() and agents_skills.is_dir() and not agents_skills.is_symlink():
        claude_skills.unlink()
        agents_skills.rename(claude_skills)
        agents_skills.symlink_to("../.claude/skills")
        print(f"  flipped skills: .claude/skills real, .agents/skills -> symlink")
    elif agents_skills.is_symlink() and claude_skills.is_dir():
        print(f"  skills already Claude-canonical")
    elif claude_skills.is_dir() and not agents_skills.exists():
        agents_skills.parent.mkdir(parents=True, exist_ok=True)
        agents_skills.symlink_to("../.claude/skills")
        print(f"  linked .agents/skills -> .claude/skills")


def ensure_layout(repo: Path) -> None:
    claude = repo / ".claude"
    agents = repo / ".agents"
    cursor = repo / ".cursor"
    claude.mkdir(exist_ok=True)
    agents.mkdir(exist_ok=True)
    cursor.mkdir(exist_ok=True)

    flip_skills_to_claude(repo)

    # skills / agents: .agents -> .claude when .claude has the real tree
    for name in ("skills", "agents"):
        src = claude / name
        dst = agents / name
        if src.is_dir() and not src.is_symlink():
            ensure_symlink(dst, f"../.claude/{name}")
        elif dst.is_dir() and not dst.is_symlink() and not src.exists():
            # leave .agents real only if nothing under .claude yet
            pass

    workflows = agents / "workflows"
    workflows.mkdir(exist_ok=True)
    readme = workflows / "README.md"
    if not readme.exists():
        readme.write_text(WORKFLOWS_README)

    ensure_symlink(cursor / "commands", "../.agents/workflows")
    if (claude / "agents").is_dir():
        ensure_symlink(cursor / "agents", "../.claude/agents")
    (cursor / "rules").mkdir(exist_ok=True)


def ensure_gitignore(repo: Path) -> None:
    gi = repo / ".gitignore"
    text = gi.read_text() if gi.exists() else ""
    if ".agents/*" in text and "!.agents/workflows" in text:
        return
    if not text.endswith("\n"):
        text += "\n"
    gi.write_text(text + GITIGNORE_BLOCK)
    print("  updated .gitignore")


def vendor_sync(repo: Path) -> None:
    dst = repo / "tools" / "sync_agent_rules.py"
    dst.parent.mkdir(exist_ok=True)
    shutil.copy2(HOST_SYNC, dst)
    print(f"  vendored sync -> {dst}")


def run_sync(repo: Path) -> int:
    import subprocess

    return subprocess.call(
        [sys.executable, str(repo / "tools" / "sync_agent_rules.py")],
        cwd=repo,
    )


def migrate(
    repo: Path,
    *,
    display: str,
    framing: str,
    critical: str | None,
    guards: dict,
    hooks_note: str,
    force: bool,
) -> int:
    print(f"== {repo}")
    claude_md = repo / "CLAUDE.md"
    if not claude_md.is_file():
        print("  error: no CLAUDE.md", file=sys.stderr)
        return 1
    existing = claude_md.read_text()
    if "@AGENTS.md" in existing and not force:
        print("  already migrated (CLAUDE.md imports AGENTS.md); use --force to redo")
        # still vendor + sync + layout
        ensure_layout(repo)
        ensure_gitignore(repo)
        vendor_sync(repo)
        return run_sync(repo)

    # Prefer hand-edited CLAUDE when still SoT; else AGENTS without generated junk
    source = existing
    if "@AGENTS.md" in existing:
        source = (repo / "AGENTS.md").read_text()

    agents_body = build_agents_md(source, framing=framing, critical=critical)
    (repo / "AGENTS.md").write_text(agents_body)
    claude_md.write_text(thin_claude(display, hooks_note))
    (repo / ".agent-guards.json").write_text(
        json.dumps(guards, indent=2) + "\n"
    )
    print("  wrote AGENTS.md, CLAUDE.md, .agent-guards.json")

    ensure_layout(repo)
    ensure_gitignore(repo)
    vendor_sync(repo)

    # Drop obsolete Antigravity AGENTS copy under .agents/ if present
    extra = repo / ".agents" / "AGENTS.md"
    if extra.is_file():
        extra.unlink()
        print("  removed .agents/AGENTS.md")

    return run_sync(repo)


