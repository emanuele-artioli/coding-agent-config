def build_agents_md(source: str, *, framing: str, critical: str | None) -> str:
    text = GENERATED_BANNER.sub("", source)
    text = HOST_BLOCK.sub("\n", text)
    text = OLD_HOST_TAIL.sub("\n", text)
    text = SHARED_IMPORT.sub("\n\n", text)
    if OLD_FRAMING.search(text):
        text = OLD_FRAMING.sub(framing, text, count=1)
    else:
        # Insert framing after the first blank-line-separated intro block
        parts = text.split("\n\n", 1)
        if len(parts) == 2:
            text = parts[0] + "\n\n" + framing + parts[1]
        else:
            text = text.rstrip() + "\n\n" + framing
    text = soft_claudeisms(text).rstrip() + "\n"
    if critical and "<!-- copilot-critical:start -->" not in text:
        # Place critical block right after framing paragraph
        needle = framing.rstrip() + "\n"
        if needle in text:
            text = text.replace(needle, needle + "\n" + critical.strip() + "\n\n", 1)
        else:
            text = framing + critical.strip() + "\n\n" + text
    return text


